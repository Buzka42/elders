#!/usr/bin/env python3
"""Build both addons: copy MetaKit into Libs/, convert art into Media/, write Media.lua, optionally install/zip.

usage: build.py [--no-art] [--install "<WoW>/_<flavor>_/Interface/AddOns"] [--zip]
"""
import argparse
import json
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]              # elders/
PROJECTS = ROOT.parent
METAKIT = ROOT / "MetaKit"
ADDONS = {
    "Elders": ROOT / "Elders",
    "Bloodsports": PROJECTS / "bloodsports" / "Bloodsports",
}
EXTRA_INSTALL = [p for p in [ROOT / "tools" / "MetaProbe"] if p.exists()]  # dev-only probe, kept local
ART_MANIFEST = ROOT / "tools" / "art" / "manifest.json"

# Which art goes into which addon (by name prefix / exact name).
ART_SPLIT = {
    "Elders": ("logo_elders", "elder_rank_", "frame_elders", "tile_elders", "header_elders", "footer_elders",
               "portrait_elder", "glyph_leaf", "seal_vote", "banner_sealed", "icon_elders", "hof_laurel"),
    "Bloodsports": ("logo_bloodsports", "crest_", "badge_", "hof_laurel", "tile_bloodsports", "header_bloodsports",
                    "footer_bloodsports", "portrait_bookie", "glyph_blades", "seal_verified", "seal_referee",
                    "seal_unverified", "icon_challenge", "icon_champion", "icon_bloodsports", "banner_victory",
                    "banner_defeat", "ring_"),
}


def copy_metakit() -> None:
    for name, addon in ADDONS.items():
        dest = addon / "Libs" / "MetaKit"
        # overwrite in place (no rmtree) so agents/tests running concurrently never see a half-empty Libs dir
        shutil.copytree(METAKIT, dest, ignore=shutil.ignore_patterns("*.md", "__pycache__"), dirs_exist_ok=True)
        print(f"MetaKit -> {dest.relative_to(PROJECTS)}")


def build_art(do_convert: bool) -> None:
    sys.path.insert(0, str(ROOT / "tools" / "art"))
    import convert  # noqa: E402  (tools/art/convert.py)

    entries = json.loads(ART_MANIFEST.read_text())
    for name, addon in ADDONS.items():
        media = addon / "Media"
        media.mkdir(exist_ok=True)
        if do_convert:
            for e in entries:
                if not e["name"].startswith(ART_SPLIT[name]):
                    continue
                if not (ART_MANIFEST.parent / e["src"]).exists():
                    continue
                out = convert.convert({**e, "out": str(media.relative_to(ART_MANIFEST.parent, walk_up=True))},
                                      ART_MANIFEST.parent)
                print(f"  art {out.name}")
            shutil.rmtree(media / "_preview", ignore_errors=True)
        have = sorted(p.stem for p in media.glob("*.tga"))
        lines = [
            "-- Generated by tools/build.py: art files present in Media/ (missing art falls back to stock textures).",
            "local ADDON, ns = ...",
            f'ns.Media = {{ path = "Interface\\\\AddOns\\\\" .. ADDON .. "\\\\Media\\\\", has = {{',
        ]
        lines += [f"  {n} = true," for n in have]
        lines += ["} }", ""]
        (addon / "Media.lua").write_text("\n".join(lines))
        print(f"{name}: Media.lua lists {len(have)} textures")


def install(target: Path) -> None:
    target.mkdir(parents=True, exist_ok=True)
    for src in [*ADDONS.values(), *EXTRA_INSTALL]:
        dest = target / src.name
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(src, dest, ignore=shutil.ignore_patterns("_preview", "*.md"))
        print(f"installed {src.name} -> {dest}")


def make_zips() -> None:
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    for name, addon in ADDONS.items():
        zpath = dist / f"{name}.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for f in addon.rglob("*"):
                if f.is_file() and "_preview" not in f.parts:
                    z.write(f, Path(name) / f.relative_to(addon))
        print(f"zip {zpath.relative_to(PROJECTS)}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-art", action="store_true", help="skip art conversion (Media.lua still regenerated)")
    ap.add_argument("--install", type=Path, help="copy Elders and Bloodsports into this AddOns folder")
    ap.add_argument("--zip", action="store_true", help="write dist/<Addon>.zip")
    args = ap.parse_args()
    copy_metakit()
    build_art(not args.no_art)
    if args.install:
        install(args.install)
    if args.zip:
        make_zips()


if __name__ == "__main__":
    main()
